#!/usr/bin/env python3
"""
Turn NIST ACVP ML-KEM test vectors into a C header for the ESP32-S3 firmware.

The vectors come from NIST's own ACVP-Server repository, which is the
authoritative source for FIPS 203 conformance testing:

    https://github.com/usnistgov/ACVP-Server/tree/<version>/gen-val/json-files

This matters. mlkem-native ships its own test vectors, but those are generated
by mlkem-native itself - checking the library against them proves internal
consistency, not conformance. Only vectors produced independently of the
implementation under test can decide whether something is ML-KEM.

The generated header is committed alongside this script, together with the
SHA-256 of every input file, so the firmware's test data can be audited without
network access and regenerated byte-for-byte with it.

Usage:
    python3 generate_kat_header.py --acvp-dir <dir> --out <header.h>
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

# The project measures and verifies these two parameter sets; see docs/roadmap.md.
LEVELS = {
    "ML-KEM-512": 512,
    "ML-KEM-768": 768,
}

KEYGEN = "ML-KEM-keyGen-FIPS203"
ENCAPDECAP = "ML-KEM-encapDecap-FIPS203"


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_pair(acvp_dir: Path, name: str):
    """Load prompt/expectedResults and index the expected values by tcId."""
    prompt = json.loads((acvp_dir / name / "prompt.json").read_text())
    expected = json.loads((acvp_dir / name / "expectedResults.json").read_text())
    by_tc = {}
    for group in expected["testGroups"]:
        for test in group["tests"]:
            by_tc[test["tcId"]] = test
    return prompt, by_tc


def c_flags(name: str, flags: list[bool]) -> str:
    """Emit the expected verdicts for a key-check group as 0/1."""
    if not flags:
        return ""
    body = "".join(f"{int(f)}," for f in flags)
    return f"static const uint8_t {name}[{len(flags)}] = {{{body}}};\n"


def c_array(name: str, rows: list[bytes]) -> str:
    """Emit a 2D uint8_t array. Empty input yields nothing."""
    if not rows:
        return ""
    width = len(rows[0])
    if any(len(r) != width for r in rows):
        raise ValueError(f"{name}: inconsistent row lengths")

    out = [f"static const uint8_t {name}[{len(rows)}][{width}] = {{"]
    for row in rows:
        body = []
        for i in range(0, width, 16):
            body.append("    " + "".join(f"0x{b:02x}," for b in row[i : i + 16]))
        out.append("  {\n" + "\n".join(body) + "\n  },")
    out.append("};\n")
    return "\n".join(out)


def collect(acvp_dir: Path, limit: int | None):
    """Pull the vectors we run, grouped per parameter set."""
    data = {lvl: {} for lvl in LEVELS.values()}

    prompt, expected = load_pair(acvp_dir, KEYGEN)
    for group in prompt["testGroups"]:
        lvl = LEVELS.get(group["parameterSet"])
        if lvl is None:
            continue
        tests = group["tests"][:limit] if limit else group["tests"]
        data[lvl]["keygen"] = [
            {
                "d": bytes.fromhex(t["d"]),
                "z": bytes.fromhex(t["z"]),
                "ek": bytes.fromhex(expected[t["tcId"]]["ek"]),
                "dk": bytes.fromhex(expected[t["tcId"]]["dk"]),
            }
            for t in tests
        ]

    prompt, expected = load_pair(acvp_dir, ENCAPDECAP)
    for group in prompt["testGroups"]:
        lvl = LEVELS.get(group["parameterSet"])
        if lvl is None:
            continue
        function = group.get("function")
        tests = group["tests"][:limit] if limit else group["tests"]

        if function == "encapsulation":
            data[lvl]["encap"] = [
                {
                    "ek": bytes.fromhex(t["ek"]),
                    "m": bytes.fromhex(t["m"]),
                    "c": bytes.fromhex(expected[t["tcId"]]["c"]),
                    "k": bytes.fromhex(expected[t["tcId"]]["k"]),
                }
                for t in tests
            ]
        elif function == "decapsulation":
            data[lvl]["decap"] = [
                {
                    "dk": bytes.fromhex(t["dk"]),
                    "c": bytes.fromhex(t["c"]),
                    "k": bytes.fromhex(expected[t["tcId"]]["k"]),
                }
                for t in tests
            ]
        elif function == "encapsulationKeyCheck":
            # FIPS 203 section 7.2: a public key whose coefficients are not
            # canonically reduced must be rejected. Half of each group is valid,
            # half is not - a check that always says "invalid" scores 50%.
            data[lvl]["ek_check"] = [
                {
                    "key": bytes.fromhex(t["ek"]),
                    "valid": bool(expected[t["tcId"]]["testPassed"]),
                }
                for t in tests
            ]
        elif function == "decapsulationKeyCheck":
            # Rejects a private key whose embedded public-key hash does not match.
            data[lvl]["dk_check"] = [
                {
                    "key": bytes.fromhex(t["dk"]),
                    "valid": bool(expected[t["tcId"]]["testPassed"]),
                }
                for t in tests
            ]

    return data


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--acvp-dir", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--acvp-version", default="v1.1.0.43")
    ap.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Cap the vectors per group (default: all of them)",
    )
    args = ap.parse_args()

    inputs = sorted(args.acvp_dir.rglob("*.json"))
    if not inputs:
        print(f"no JSON files under {args.acvp_dir}", file=sys.stderr)
        return 1

    data = collect(args.acvp_dir, args.limit)

    lines = [
        "/*",
        " * NIST ACVP test vectors for ML-KEM (FIPS 203).",
        " *",
        " * GENERATED FILE - do not edit by hand.",
        " * Regenerate with tests/acvp/generate_kat_header.py.",
        " *",
        f" * Source: usnistgov/ACVP-Server {args.acvp_version}",
        " *         gen-val/json-files/ML-KEM-{keyGen,encapDecap}-FIPS203",
        " *",
        " * Input files and their SHA-256:",
    ]
    for path in inputs:
        rel = path.relative_to(args.acvp_dir)
        lines.append(f" *   {rel}")
        lines.append(f" *     {sha256_of(path)}")
    lines += [
        " */",
        "",
        "#ifndef ACVP_VECTORS_H",
        "#define ACVP_VECTORS_H",
        "",
        "#include <stdint.h>",
        "",
        f'#define ACVP_VERSION "{args.acvp_version}"',
        "",
    ]

    for lvl in sorted(data):
        groups = data[lvl]
        lines.append(f"/* ---------- ML-KEM-{lvl} ---------- */")
        lines.append("")

        if "keygen" in groups:
            rows = groups["keygen"]
            lines.append(f"#define KAT{lvl}_KEYGEN_COUNT {len(rows)}")
            for field in ("d", "z", "ek", "dk"):
                lines.append(c_array(f"kat{lvl}_keygen_{field}", [r[field] for r in rows]))

        if "encap" in groups:
            rows = groups["encap"]
            lines.append(f"#define KAT{lvl}_ENCAP_COUNT {len(rows)}")
            for field in ("ek", "m", "c", "k"):
                lines.append(c_array(f"kat{lvl}_encap_{field}", [r[field] for r in rows]))

        if "decap" in groups:
            rows = groups["decap"]
            lines.append(f"#define KAT{lvl}_DECAP_COUNT {len(rows)}")
            for field in ("dk", "c", "k"):
                lines.append(c_array(f"kat{lvl}_decap_{field}", [r[field] for r in rows]))

        for tag, key in (("EKCHECK", "ek_check"), ("DKCHECK", "dk_check")):
            if key not in groups:
                continue
            rows = groups[key]
            prefix = f"kat{lvl}_{key.replace('_', '')}"
            lines.append(f"#define KAT{lvl}_{tag}_COUNT {len(rows)}")
            lines.append(c_array(f"{prefix}_key", [r["key"] for r in rows]))
            lines.append(c_flags(f"{prefix}_valid", [r["valid"] for r in rows]))

    lines += ["#endif /* ACVP_VECTORS_H */", ""]

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))

    print(f"wrote {args.out} ({args.out.stat().st_size / 1024:.0f} KB)")
    for lvl in sorted(data):
        counts = {k: len(v) for k, v in data[lvl].items()}
        print(f"  ML-KEM-{lvl}: {counts}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
